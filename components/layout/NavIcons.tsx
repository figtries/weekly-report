/**
 * The sidebar's own icons, drawn by hand (30 Sep 2026, supplied as SVG).
 *
 * Every path paints with `currentColor`, not the #727272 they were drawn in:
 * the row decides the colour (grey at rest, blue when it is the current
 * page), and a hard-coded grey would have stayed grey on the blue pill.
 *
 * The icons come in slightly different native sizes (18 to 20px), so each one
 * keeps its own and is CENTRED in a fixed 18px box rather than squeezed into
 * it. The box is what the menu lays out (and what the label column at 54px is
 * measured from, see `Brand`); the glyph is free to overhang it by a pixel.
 * Scaling them all to 18px would have made the 20px ones read smaller than the
 * 18px Data Overall beside them.
 */
function NavIcon({
  width,
  height,
  className,
  children,
}: {
  width: number;
  height: number;
  className?: string;
  children: ReactNode;
}) {
  return (
    <span aria-hidden className={cn('relative block size-[18px] shrink-0', className)}>
      <svg
        width={width}
        height={height}
        viewBox={`0 0 ${width} ${height}`}
        fill="none"
        xmlns="http://www.w3.org/2000/svg"
        className="absolute left-1/2 top-1/2 -translate-x-1/2 -translate-y-1/2"
      >
        {children}
      </svg>
    </span>
  );
}

